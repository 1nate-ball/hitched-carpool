begin;

create table public.destinations (
  id text primary key,
  name text not null check (length(btrim(name)) > 0)
);

insert into public.destinations (id, name) values
  ('slc', 'Salt Lake City'),
  ('sundance', 'Sundance'),
  ('parkcity', 'Park City'),
  ('bearlake', 'Bear Lake'),
  ('moab', 'Moab'),
  ('stgeorge', 'St. George'),
  ('zion', 'Zion National Park'),
  ('jackson', 'Jackson Hole');

create table public.trips (
  id uuid primary key default gen_random_uuid(),
  driver_id uuid not null default auth.uid() references auth.users(id),
  destination_id text not null references public.destinations(id),
  departure_at timestamptz not null,
  pickup_location text not null check (length(btrim(pickup_location)) > 0),
  dropoff_location text not null check (length(btrim(dropoff_location)) > 0),
  total_seats integer not null check (total_seats between 1 and 7),
  price_per_seat integer not null check (price_per_seat between 1 and 150),
  return_at timestamptz,
  created_at timestamptz not null default now(),
  constraint return_after_departure check (return_at is null or return_at > departure_at)
);

create index trips_driver_id_idx on public.trips (driver_id);
create index trips_destination_departure_idx on public.trips (destination_id, departure_at);

-- Validate at creation, not with a time-dependent CHECK on stored historical rows.
-- Default SECURITY INVOKER; this function does not bypass RLS.
create function public.validate_new_trip_departure()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.departure_at <= clock_timestamp() then
    raise exception 'Departure must be in the future.' using errcode = '23514';
  end if;
  return new;
end;
$$;
revoke all on function public.validate_new_trip_departure() from public, anon, authenticated;
create trigger validate_new_trip_departure
before insert on public.trips
for each row execute function public.validate_new_trip_departure();

alter table public.destinations enable row level security;
alter table public.trips enable row level security;
revoke all on public.destinations, public.trips from public, anon, authenticated;
grant usage on schema public to authenticated;
grant select on public.destinations, public.trips to authenticated;
-- IDs and creation times are generated by the database, not accepted from the form.
grant insert (driver_id, destination_id, departure_at, pickup_location,
  dropoff_location, total_seats, price_per_seat, return_at)
on public.trips to authenticated;

create policy destinations_read_signed_in on public.destinations
for select to authenticated using ((select auth.uid()) is not null);

-- Draft product assumption: all signed-in users can browse trips.
-- This does NOT establish BYU affiliation or identity verification.
create policy trips_read_signed_in on public.trips
for select to authenticated using ((select auth.uid()) is not null);

create policy trips_insert_own on public.trips
for insert to authenticated
with check ((select auth.uid()) = driver_id);

-- Editing, deletion, requests, chat, and verification are outside this draft.
commit;
